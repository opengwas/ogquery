@pytest.mark.parametrize("module", sorted(PUBLIC_NAMES))
def test_every_public_name_of_the_store_reader_exists(module: str) -> None:
    imported = importlib.import_module(module)
    missing = [name for name in PUBLIC_NAMES[module] if not hasattr(imported, name)]
    assert not missing, f"{module} lacks {missing}, public in opengwasdb {OPENGWASDB_COMMIT[:8]}"


def test_the_clumps_and_range_names_this_catch_up_added_are_listed() -> None:
    assert "MalformedClumps" in PUBLIC_NAMES["ogquery.top_hits"]
    assert "declares_clumps_of" in PUBLIC_NAMES["ogquery.top_hits"]
    assert "narrowed_range_question" in PUBLIC_NAMES["ogquery.digests"]
    assert "RANGE_ROWS_ASKED" in PUBLIC_NAMES["ogquery.digests"]
